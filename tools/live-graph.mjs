// The import graph of a project's JS/TS sources, for the live page's graph view. No dependencies; nothing is executed or written.
//   parseSpecs(text)       the module specifiers a source text names (import / export-from / require / import()), string literals only
//   resolveSpec(...)       which scanned file a specifier names (never touches the disk)
//   buildGraph(root, prev) walks the project and returns { graph, cache }; `cache` makes the next build read only what changed
// A file is read only if it is a regular file inside the root (links are never followed), is not secret or generated by the same
// rules as hooks/files.ts, and is small. What is left out is counted, never named.
import { constants } from 'node:fs'
import { lstat, open, readdir } from 'node:fs/promises'
import { join } from 'node:path'

export const GRAPH_VERSION = 1
export const LIMITS = { files: 5000, depth: 20, fileBytes: 256 * 1024, totalBytes: 32 * 1024 * 1024, edges: 20000, ms: 1500, tsconfigBytes: 64 * 1024 }

const CODE_EXT = /\.(?:[cm]?[jt]s|[jt]sx)$/
const EXTENSIONS = ['.ts', '.tsx', '.d.ts', '.mts', '.d.mts', '.cts', '.d.cts', '.js', '.jsx', '.mjs', '.cjs']
const JS_TO_TS = { '.js': ['.ts', '.tsx', '.d.ts'], '.jsx': ['.tsx'], '.mjs': ['.mts', '.d.mts'], '.cjs': ['.cts', '.d.cts'] }
const SKIP_DIRS = new Set(['.git', 'node_modules', 'dist', 'build', 'out', 'coverage', '.next', 'target', 'vendor', '.claude'])

// The category rules of hooks/files.ts (a test keeps the two in step): a file is read only if it is none of secret and generated.
export const SECRET = /(^|\/)(\.env(?:\.(?!(?:example|sample|template|dist)$)[^/]*)?|\.envrc|\.npmrc|\.netrc|\.pgpass|\.pypirc|\.git-credentials|credentials(\.json)?|id_(?:rsa|dsa|ecdsa|ed25519)[^/]*|[^/]*\.(pem|key|p12|pfx)|\.kube\/config|\.ssh\/(?!known_hosts$|config$)[^/]+)$/i
export const GENERATED = /(^|\/)(dist|build|out|coverage|node_modules|\.next|target|vendor)\/|(^|\/)(package-lock\.json|pnpm-lock\.yaml|yarn\.lock|bun\.lockb?|Cargo\.lock|poetry\.lock|go\.sum)$|\.min\.(js|css)$|\.map$/
const TEST = /(^|\/)(tests?|__tests__|spec|e2e)\/|\.(test|spec)\.[cm]?[jt]sx?$/
const CONFIG = /(^|\/)(package\.json|tsconfig[^/]*\.json)$|(^|\/)\.(github|claude|vscode|husky)\/|\.config\.[cm]?[jt]s$|(^|\/)\.[^/]*rc(\.json|\.js)?$/
export const kindOfPath = path => (SECRET.test(path) ? 'secret' : GENERATED.test(path) ? 'generated' : TEST.test(path) ? 'test' : CONFIG.test(path) ? 'config' : 'source')

const NOT_A_VALUE = new Set(['return', 'typeof', 'case', 'in', 'of', 'delete', 'void', 'throw', 'new', 'else', 'do', 'yield', 'await'])
const isWordChar = ch => ch !== undefined && /[A-Za-z0-9_$]/.test(ch)

/**
 * The specifiers a source text names, as [spec, kind] with kind 'i' (import, require), 'r' (export … from) or 'd' (import('x')).
 * A small scanner: comments, strings and template literals are skipped, so a specifier inside one is not taken. A regular expression
 * literal is told from a division by the token before it (good enough here; a miss costs an edge, never a read).
 */
export function parseSpecs(text) {
  const out = []
  const n = text.length
  let i = 0
  let prev = '' // the last significant token: a word, a punctuation character, or 'str'
  let prev2 = ''
  let stmt = 'import' // the last import/export word seen
  const push = token => {
    prev2 = prev
    prev = token
  }
  const readString = () => {
    const quote = text[i]
    let value = ''
    i++
    while (i < n && text[i] !== quote && text[i] !== '\n') {
      if (text[i] === '\\') {
        value += text[i + 1] ?? ''
        i += 2
      } else value += text[i++]
    }
    if (text[i] === quote) i++
    return value
  }
  const skipTemplate = () => {
    i++ // the opening backtick
    while (i < n) {
      const ch = text[i]
      if (ch === '\\') i += 2
      else if (ch === '`') {
        i++
        return
      } else if (ch === '$' && text[i + 1] === '{') {
        i += 2
        let depth = 1
        while (i < n && depth > 0) {
          const c = text[i]
          if (c === '{') depth++
          else if (c === '}') depth--
          else if (c === '`') {
            skipTemplate()
            continue
          } else if (c === '"' || c === "'") {
            readString()
            continue
          }
          i++
        }
      } else i++
    }
  }
  const nextNonSpace = from => {
    let k = from
    while (k < n && /\s/.test(text[k])) k++
    return text[k]
  }
  while (i < n) {
    const ch = text[i]
    if (/\s/.test(ch)) {
      i++
    } else if (ch === '/' && text[i + 1] === '/') {
      while (i < n && text[i] !== '\n') i++
    } else if (ch === '/' && text[i + 1] === '*') {
      const end = text.indexOf('*/', i + 2)
      i = end < 0 ? n : end + 2
    } else if (ch === '`') {
      skipTemplate()
      push('str')
    } else if (ch === '"' || ch === "'") {
      const value = readString()
      const afterParen = prev === '(' && (prev2 === 'require' || prev2 === 'import')
      if (prev === 'from' || prev === 'import') out.push([value, prev === 'from' && stmt === 'export' ? 'r' : 'i'])
      else if (afterParen && /^[),]$/.test(nextNonSpace(i) ?? '')) out.push([value, prev2 === 'import' ? 'd' : 'i'])
      push('str')
    } else if (ch === '/') {
      // A slash after a value is a division; after an operator, a keyword or the start of a statement, a regular expression.
      const value = prev === 'str' || prev === ')' || prev === ']' || prev === '}' || (isWordChar(prev[0]) && !NOT_A_VALUE.has(prev))
      i++
      if (value) push('/')
      else {
        let inClass = false
        while (i < n && text[i] !== '\n') {
          if (text[i] === '\\') i += 2
          else if (text[i] === '[') (inClass = true), i++
          else if (text[i] === ']') (inClass = false), i++
          else if (text[i] === '/' && !inClass) {
            i++
            break
          } else i++
        }
        while (i < n && isWordChar(text[i])) i++
        push('str')
      }
    } else if (isWordChar(ch)) {
      let j = i
      while (j < n && isWordChar(text[j])) j++
      const word = text.slice(i, j)
      // `x.from` and `x.require` are properties, not keywords.
      if (prev !== '.') {
        if (word === 'import' || word === 'export') stmt = word
        push(word)
      } else push('prop')
      i = j
    } else {
      push(ch)
      i++
    }
  }

  return out
}

const dirOf = path => {
  const at = path.lastIndexOf('/')

  return at < 0 ? '' : path.slice(0, at)
}

// `a/b/../c` → `a/c`; null when it climbs out of the root.
function normalize(path) {
  const parts = []
  for (const part of path.split('/')) {
    if (part === '' || part === '.') continue
    if (part === '..') {
      if (parts.length === 0) return null
      parts.pop()
    } else parts.push(part)
  }

  return parts.join('/')
}

/** The scanned file a specifier names, or null. `files` is a Set of root-relative posix paths; `aliases` comes from the tsconfig. */
export function resolveSpec(fromPath, spec, files, aliases = { baseUrl: null, pathsBase: '', paths: [] }) {
  const tryBase = base => {
    if (base === null) return null
    // The project root itself (`import x from '.'`) is its index file.
    if (base === '') {
      for (const ext of EXTENSIONS) if (files.has(`index${ext}`)) return `index${ext}`

      return null
    }
    if (files.has(base)) return base
    for (const ext of EXTENSIONS) if (files.has(base + ext)) return base + ext
    const ext = /\.[cm]?jsx?$/.exec(base)?.[0]
    if (ext && JS_TO_TS[ext]) {
      const stem = base.slice(0, -ext.length)
      for (const to of JS_TO_TS[ext]) if (files.has(stem + to)) return stem + to
    }
    for (const ext2 of EXTENSIONS) if (files.has(`${base}/index${ext2}`)) return `${base}/index${ext2}`

    return null
  }
  if (spec.startsWith('./') || spec.startsWith('../') || spec === '.' || spec === '..') return tryBase(normalize(`${dirOf(fromPath)}/${spec}`))
  for (const alias of aliases.paths) {
    // A pattern without a "*" names one specifier exactly; the base of the targets is the baseUrl, else the tsconfig's own folder.
    if (alias.wild === false ? spec !== alias.prefix : !spec.startsWith(alias.prefix) || !spec.endsWith(alias.suffix) || spec.length < alias.prefix.length + alias.suffix.length) continue
    const middle = alias.wild === false ? '' : spec.slice(alias.prefix.length, spec.length - alias.suffix.length)
    for (const target of alias.targets) {
      const got = tryBase(normalize(`${aliases.pathsBase ?? aliases.baseUrl ?? ''}/${target.replace('*', middle)}`))
      if (got) return got
    }
  }
  // A bare name is an outside package unless the tsconfig's baseUrl makes it a path inside the project.
  if (aliases.baseUrl !== null && !spec.startsWith('/') && !spec.startsWith('@')) return tryBase(normalize(`${aliases.baseUrl}/${spec}`))

  return null
}

const stripJsonComments = text => {
  let out = ''
  for (let i = 0; i < text.length; i++) {
    const ch = text[i]
    if (ch === '"') {
      let j = i + 1
      while (j < text.length && text[j] !== '"') j += text[j] === '\\' ? 2 : 1
      out += text.slice(i, j + 1)
      i = j
    } else if (ch === '/' && text[i + 1] === '/') {
      while (i < text.length && text[i] !== '\n') i++
    } else if (ch === '/' && text[i + 1] === '*') {
      const end = text.indexOf('*/', i + 2)
      i = end < 0 ? text.length : end + 1
    } else out += ch
  }

  return out.replace(/,(\s*[}\]])/g, '$1')
}

// baseUrl and paths of the root tsconfig.json (extends is not followed); a pattern holds at most one "*".
async function readAliases(root) {
  const none = { baseUrl: null, pathsBase: '', paths: [] }
  try {
    const path = join(root, 'tsconfig.json')
    const info = await lstat(path)
    if (!info.isFile() || info.size > LIMITS.tsconfigBytes) return none
    const options = JSON.parse(stripJsonComments((await readSmall(path, info)) ?? '{}')).compilerOptions ?? {}
    const baseUrl = typeof options.baseUrl === 'string' ? normalize(options.baseUrl) : null
    const paths = []
    if (options.paths && typeof options.paths === 'object') {
      for (const [pattern, targets] of Object.entries(options.paths)) {
        if (pattern.split('*').length > 2 || !Array.isArray(targets)) continue
        const at = pattern.indexOf('*')
        paths.push({ wild: at >= 0, prefix: at < 0 ? pattern : pattern.slice(0, at), suffix: at < 0 ? '' : pattern.slice(at + 1), targets: targets.filter(one => typeof one === 'string' && one.split('*').length <= 2).slice(0, 5) })
      }
    }

    return { baseUrl, pathsBase: baseUrl ?? '', paths }
  } catch {
    return none
  }
}

// Opens without following a link and reads only if what was opened is the file that was looked at.
async function readSmall(path, seen) {
  const handle = await open(path, constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0) | (constants.O_NONBLOCK ?? 0))
  try {
    const info = await handle.stat()
    if (!info.isFile() || info.size !== seen.size || (seen.ino && info.ino !== seen.ino)) return null

    return await handle.readFile('utf8')
  } finally {
    await handle.close()
  }
}

/**
 * Walks `root` and returns { graph, cache }. `prev` is the cache of the last build: a file whose size and mtime are the same is not read again.
 * The graph is { v, builtAt, ms, truncated, skipped, unresolved, nodes: [{ p, c, l, s, big?, ext }], edges: [[from, to, kind]] } with kind i | r | d | t.
 */
export async function buildGraph(root, prev = new Map(), now = Date.now) {
  const started = now()
  const truncated = {}
  const skipped = { secret: 0, generated: 0, big: 0, link: 0 }
  const found = [] // { p, c, size, mtimeMs, ino }
  const walk = async (dir, rel, depth) => {
    if (depth > LIMITS.depth) return void (truncated.depth = true)
    let entries
    try {
      entries = await readdir(dir, { withFileTypes: true })
    } catch {
      return
    }
    entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    for (const entry of entries) {
      if (now() - started > LIMITS.ms) return void (truncated.time = true)
      const path = rel === '' ? entry.name : `${rel}/${entry.name}`
      if (entry.isSymbolicLink()) {
        skipped.link++
        continue
      }
      if (entry.isDirectory()) {
        if (!SKIP_DIRS.has(entry.name)) await walk(join(dir, entry.name), path, depth + 1)
        else if (entry.name !== '.git' && entry.name !== '.claude') skipped.generated++
        continue
      }
      if (!entry.isFile()) continue
      const kind = kindOfPath(path)
      if (kind === 'secret') {
        skipped.secret++
        continue
      }
      if (kind === 'generated' || !CODE_EXT.test(entry.name)) continue
      if (found.length >= LIMITS.files) return void (truncated.files = true)
      try {
        const info = await lstat(join(dir, entry.name))
        if (info.isFile()) found.push({ p: path, c: kind, size: info.size, mtimeMs: info.mtimeMs, ctimeMs: info.ctimeMs, ino: info.ino })
      } catch {
        // gone while walking
      }
    }
  }
  await walk(root, '', 0)

  const aliases = await readAliases(root)
  const cache = new Map()
  let bytes = 0
  for (const file of found) {
    const old = prev.get(file.p)
    if (old && !old.stale && old.size === file.size && old.mtimeMs === file.mtimeMs && old.ctimeMs === file.ctimeMs && old.ino === file.ino) {
      cache.set(file.p, old)
      if (old.big) skipped.big++
      continue
    }
    // `stale` marks a file that was not read this time (out of budget, unreadable): the next build tries it again.
    // ctime and inode too: a copy that keeps the size and the modification time (cp -p, rsync -t) still changes them.
    const entry = { size: file.size, mtimeMs: file.mtimeMs, ctimeMs: file.ctimeMs, ino: file.ino, specs: [], big: false, stale: false }
    if (file.size > LIMITS.fileBytes) {
      entry.big = true
      skipped.big++
    } else if (bytes + file.size > LIMITS.totalBytes || now() - started > LIMITS.ms) {
      truncated[bytes + file.size > LIMITS.totalBytes ? 'bytes' : 'time'] = true
      entry.specs = old?.specs ?? []
      entry.stale = true
    } else {
      try {
        const text = await readSmall(join(root, ...file.p.split('/')), file)
        if (text !== null) entry.specs = parseSpecs(text)
        else entry.stale = true
        bytes += file.size
      } catch {
        // unreadable: the node stays, with no edges, and the next build tries again
        entry.stale = true
      }
    }
    cache.set(file.p, entry)
  }

  const paths = found.map(one => one.p)
  const files = new Set(paths)
  const nodes = found.map(one => ({ p: one.p, c: one.c, l: /\.tsx$/.test(one.p) ? 'tsx' : /\.[cm]?ts$/.test(one.p) ? 'ts' : 'js', s: one.size, ...(cache.get(one.p).big ? { big: 1 } : {}), ext: 0 }))
  const index = new Map(paths.map((p, at) => [p, at]))
  const edges = []
  const seen = new Set()
  const add = (from, to, kind) => {
    const key = `${from}>${to}`
    if (from === to || seen.has(key)) return
    if (edges.length >= LIMITS.edges) return void (truncated.edges = true)
    seen.add(key)
    edges.push([from, to, kind])
  }
  let unresolved = 0
  for (const file of found) {
    const from = index.get(file.p)
    for (const [spec, kind] of cache.get(file.p).specs) {
      const target = resolveSpec(file.p, spec, files, aliases)
      if (target) add(from, index.get(target), kind)
      else if (spec.startsWith('.')) {
        // A stylesheet, an image or data file is no source file: only a specifier that names code (or no extension) is a miss.
        if (!/\.[A-Za-z0-9]+(?:\?.*)?$/.test(spec.slice(spec.lastIndexOf('/') + 1)) || CODE_EXT.test(spec.replace(/\?.*$/, ''))) unresolved++
      }
      else nodes[from].ext++
    }
  }

  // A test belongs to the file it is named after, if it does not already import it.
  const stemOf = path => path.slice(path.lastIndexOf('/') + 1).replace(/\.(?:test|spec)\.[^.]+$|\.[^.]+$/, '')
  const bySource = new Map()
  for (const file of found) {
    if (file.c === 'test') continue
    const stem = stemOf(file.p)
    if (!bySource.has(stem)) bySource.set(stem, [])
    bySource.get(stem).push(file.p)
  }
  for (const file of found) {
    if (file.c !== 'test' || !/\.(?:test|spec)\./.test(file.p)) continue
    const all = bySource.get(stemOf(file.p)) ?? []
    const same = all.filter(one => dirOf(one) === dirOf(file.p))
    const target = same.length === 1 ? same[0] : same.length === 0 && all.length === 1 ? all[0] : null
    if (target) add(index.get(file.p), index.get(target), 't')
  }

  const graph = { v: GRAPH_VERSION, builtAt: Date.now(), ms: now() - started, truncated: Object.keys(truncated).length ? truncated : false, skipped, unresolved, nodes, edges }

  return { graph, cache }
}

/**
 * A cache for a server: one build at a time per project, the last answer kept for `maxAge` ms, a few projects at most.
 * The answer is the graph itself; a failed build is an error for the caller, and the next call tries again.
 */
export function graphService(build = buildGraph, keep = 4) {
  const slots = new Map() // root -> { graph, cache, at, running }

  return async function graphOf(root, maxAge = 5000) {
    const slot = slots.get(root)
    if (slot?.running) return slot.running
    if (slot?.graph && Date.now() - slot.at < maxAge) return slot.graph
    const running = build(root, slot?.cache).then(({ graph, cache }) => {
      slots.delete(root)
      slots.set(root, { graph, cache, at: Date.now() })
      // A slot whose build is still running stays, so the next call joins it instead of starting another.
      for (const [key, one] of slots) {
        if (slots.size <= keep) break
        if (key !== root && !one.running) slots.delete(key)
      }

      return graph
    }, error => {
      const now = slots.get(root)
      if (now) now.running = undefined

      throw error
    })
    slots.set(root, { ...(slot ?? {}), running })

    return running
  }
}
